import { useRef, useState } from 'react'
import { Check, Copy, ExternalLink, ImageUp, Info, Loader2 } from 'lucide-react'
import { toast } from 'sonner'
import { Button } from '@/components/ui/button'
import { masterPromptFor, type Run } from '@/ai/agents'
import { useRun } from '@/ai/runStore'
import { cn } from '@/lib/utils'

/**
 * The Art Director's concept plus the free path for imagery: copy the prompt into
 * the Gemini app (free), download the image, upload it here. Every format then
 * uses it and the QA agent re-checks the lot.
 */
export function KeyVisual({ run }: { run: Run }) {
  const uploadVisual = useRun((s) => s.uploadVisual)
  const fileRef = useRef<HTMLInputElement>(null)
  const [copied, setCopied] = useState(false)
  const [busy, setBusy] = useState(false)
  const art = run.art!
  const prompt = masterPromptFor(art, '16:9')
  const canUpload = run.status === 'review'
  const generated = run.mode === 'live' && !!run.masterImage && !run.uploadedVisual && !run.imageBlocked

  const copy = async () => {
    try {
      await navigator.clipboard.writeText(`${prompt}\nMake it a landscape 16:9 photograph.`)
      setCopied(true)
      setTimeout(() => setCopied(false), 1800)
    } catch {
      toast.error('Could not copy. Expand "Image prompt" on any card and copy it from there.')
    }
  }

  return (
    <div className="space-y-2.5 text-[13px]">
      <p className="text-[15px] leading-tight font-semibold">{art.concept}</p>
      <p className="text-xs leading-snug text-muted-foreground">{art.scene}</p>

      {run.masterImage && (
        <div className="relative">
          <img src={run.masterImage} alt="Key visual" className="aspect-video w-full rounded-lg object-cover ring-1 ring-black/10" />
          <span className="absolute top-1.5 left-1.5 rounded-md bg-black/60 px-1.5 py-0.5 text-[10px] font-medium text-white backdrop-blur-sm">
            {run.uploadedVisual ? 'Supplied key visual' : 'Generated by Gemini'}
          </span>
        </div>
      )}

      {run.imageBlocked && !run.uploadedVisual && (
        <div className="flex gap-2 rounded-lg bg-amber-500/10 p-2.5 text-[11px] leading-snug text-amber-900 ring-1 ring-amber-500/25 dark:text-amber-200">
          <Info className="mt-px size-3.5 shrink-0" />
          <span>
            This API key can&apos;t generate images ({run.imageBlocked.replace(/\.$/, '')}). Make it free in the Gemini app instead: copy the prompt, generate, download, then upload it here.
          </span>
        </div>
      )}

      {!generated && (
        <div className="space-y-1.5 rounded-lg border border-dashed p-2.5">
          <div className="text-[11px] font-semibold tracking-wide text-muted-foreground uppercase">Key visual · free route</div>
          <div className="flex flex-wrap gap-1.5">
            <Button size="sm" variant="outline" onClick={copy}>
              {copied ? <Check /> : <Copy />} {copied ? 'Copied' : '1. Copy prompt'}
            </Button>
            <Button size="sm" variant="outline" asChild>
              <a href="https://gemini.google.com/app" target="_blank" rel="noreferrer">
                <ExternalLink /> 2. Open Gemini
              </a>
            </Button>
            <Button
              size="sm"
              disabled={!canUpload || busy}
              onClick={() => fileRef.current?.click()}
              className={cn(canUpload && 'bg-brand-700 hover:bg-brand-800')}
              title={canUpload ? 'Use your image for every format' : 'Available once the agents finish'}
            >
              {busy ? <Loader2 className="animate-spin" /> : <ImageUp />} 3. Upload
            </Button>
          </div>
          <input
            ref={fileRef}
            type="file"
            accept="image/png,image/jpeg,image/webp"
            className="hidden"
            aria-label="Upload key visual"
            onChange={async (e) => {
              const file = e.target.files?.[0]
              e.target.value = ''
              if (!file) return
              setBusy(true)
              try {
                await uploadVisual(file)
                toast.success('Key visual applied to every format', { description: 'The QA agent re-checked each asset with your image.' })
              } catch (err) {
                toast.error((err as Error).message)
              } finally {
                setBusy(false)
              }
            }}
          />
        </div>
      )}

      <p className="border-t pt-2 text-xs text-muted-foreground italic">{art.mood}</p>
    </div>
  )
}
